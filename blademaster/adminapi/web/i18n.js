export function storage(kind,key,value) {
  try { if (value === undefined) return window[kind].getItem(key); value === null ? window[kind].removeItem(key) : window[kind].setItem(key,value); } catch { return null; }
}
let language = storage("localStorage","cso2-language") || (navigator.language.startsWith("zh") ? "zh" : "en");
if (!dictionaries[language]) language="en";
export const locale = () => language === "zh" ? "zh-CN" : "en-US";
export function t(key, values={}) {
  return (dictionaries[language][key] || key).replace(/\{(\w+)\}/g,(_,name)=>String(values[name] ?? ""));
}
export function translate(root=document) {
  root.querySelectorAll("[data-i18n]").forEach(el=>{el.textContent=t(el.dataset.i18n);});
  root.querySelectorAll("[data-placeholder]").forEach(el=>{el.placeholder=t(el.dataset.placeholder);});
  root.querySelectorAll("[data-aria]").forEach(el=>{el.setAttribute("aria-label",t(el.dataset.aria));});
}
export function setLanguage(value) {
  language = dictionaries[value] ? value : "en";
  storage("localStorage","cso2-language",language);
  document.documentElement.lang=locale();
  document.title = "CSO2 · "+t("console");
  document.querySelector("#language").value=language;
  translate();
}
export function setTheme(value) {
  if (!["light","dark","system"].includes(value)) value="system";
  storage("localStorage","cso2-theme",value);
  document.querySelector("#theme").value=value;
  document.documentElement.dataset.theme=value==="system" ? (matchMedia("(prefers-color-scheme: dark)").matches ? "dark":"light") : value;
}
export function initPreferences() {
  setLanguage(language);
  setTheme(storage("localStorage","cso2-theme") || "system");
  matchMedia("(prefers-color-scheme: dark)").addEventListener("change",()=>{if(document.querySelector("#theme").value==="system") setTheme("system");});
}

